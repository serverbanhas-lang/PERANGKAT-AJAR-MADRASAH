export type TingkatKelas = '10' | '11' | '12';
export type JenisKelamin = 'L' | 'P';
export type AttendanceStatus = 'H' | 'S' | 'I' | 'A';

export interface KelasItem {
  id: string;
  tingkat: TingkatKelas;
  nama: string; // e.g., "X-A", "XI-IPA-1", "XII-IPS-2"
  jurusan: string;
  waliKelas?: string;
}

export interface StudentItem {
  id: string;
  nisn: string;
  nama: string;
  jk: JenisKelamin;
  kelasId: string;
  status: 'aktif' | 'nonaktif';
}

export interface AttendanceRecord {
  // key: `${kelasId}::${tanggal}` (YYYY-MM-DD)
  [studentId: string]: AttendanceStatus;
}

export interface JournalItem {
  id: string;
  kelasId: string;
  semester: 1 | 2;
  tanggal: string; // YYYY-MM-DD
  hari: string;
  pekanKe: number;
  jpCount: number;
  mapel: string;
  tpId?: string;
  tpLabel: string;
  materi: string;
  catatan: string;
  refleksi: string;
  status: 'terjadwal' | 'terlaksana' | 'ditunda';
  autoGenerated?: boolean;
}

export interface GradeWeights {
  formatif: number; // default 40
  sumatif: number;  // default 30
  pats: number;     // default 30
}

export interface StudentGradeRow {
  formatif: Record<string, number | ''>; // tp1..tp10
  sumatif: Record<string, number | ''>;  // s1..s5
  pats: number | '';
  catatan?: string;
}

export interface GradeBookData {
  weights: GradeWeights;
  tpCount: number; // dynamic 1..10 based on Promes/TP
  rows: Record<string, StudentGradeRow>; // key: studentId
}

export interface QuizQuestion {
  id: string;
  type: 'pg' | 'esai';
  question: string;
  options: string[];
  correctAnswerIndex: number;
  explanation: string;
  essayRubric: string;
  points: number;
}

export interface QuizSubmission {
  id: string;
  submittedAt: string;
  studentId?: string;
  nisn: string;
  studentName: string;
  kelasLabel: string;
  answers: Record<string, string | number>;
  pgCorrect: number;
  pgTotal: number;
  pgScore: number;
  essayScores: Record<string, number>;
  totalScore: number;
  status: 'graded' | 'needs_essay_review';
}

export interface QuizItem {
  id: string;
  code: string;
  judul: string;
  mapel: string;
  kelasId: string;
  kelasLabel: string;
  unitId?: string;
  tpKey: string; // "tp1".."tp10"
  tpLabel: string;
  durationMinutes: number;
  isOpen: boolean;
  publishedAt?: string;
  questions: QuizQuestion[];
  submissions: QuizSubmission[];
  syncedToGradeAt?: string;
}

export type MediaPembelajaranJenis =
  | 'slide-presentasi'
  | 'peta-konsep'
  | 'kartu-ajar'
  | 'studi-kasus';

export type MediaSlideTipe =
  | 'pembuka'
  | 'tujuan'
  | 'konsep'
  | 'uraian'
  | 'contoh'
  | 'visual'
  | 'kbc'
  | 'kuis-cepat'
  | 'refleksi'
  | 'rangkuman';

export interface MediaSlideItem {
  id: string;
  judulSlide: string;
  tipe: MediaSlideTipe;
  ringkasan: string;
  poinUtama: string[];
  visualIde: string;
  catatanGuru: string;
  pertanyaanInteraktif?: string;
}

export interface LearningMediaItem {
  id: string;
  judul: string;
  subjudul?: string;
  jenis: MediaPembelajaranJenis;
  mapel: string;
  kelasId: string;
  kelasLabel: string;
  unitId?: string;
  materiJudul?: string;
  tujuanPembelajaran?: string;
  integrasiKbc?: string;
  aktivitasKelas?: string;
  durasiMenit: number;
  createdAt: string;
  updatedAt: string;
  slides: MediaSlideItem[];
  glosarium?: Array<{ istilah: string; makna: string }>;
}

export interface AdminGuruState {
  classes: KelasItem[];
  students: StudentItem[];
  // key: `${kelasId}::${tanggal}`
  attendance: Record<string, AttendanceRecord>;
  journals: JournalItem[];
  // key: `${kelasId}::${mapelKey}`
  grades: Record<string, GradeBookData>;
  quizzes: QuizItem[];
  mediaPembelajaran: LearningMediaItem[];
}

