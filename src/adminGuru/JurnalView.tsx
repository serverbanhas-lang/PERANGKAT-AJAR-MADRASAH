import React, { useMemo, useState } from 'react';
import {
  CalendarRange,
  Plus,
  Printer,
  Sparkles,
  Trash2,
  Users,
} from 'lucide-react';
import {
  autoGenerateJournals,
  computeAttendanceSummary,
  createUid,
  formatTanggalID,
  getActiveMapelList,
  getAdminGuruState,
  getAppApi,
  getDayCalendarStatus,
  getIndonesianDayName,
  getLegacyState,
  updateAdminGuruState,
} from './bridge';
import type { JournalItem, TingkatKelas } from '../types/adminGuru';

export const JurnalView: React.FC = () => {
  const [adminState, setAdminState] = useState(() => getAdminGuruState());
  const legacy = getLegacyState();
  const api = getAppApi();

  const mapelList = useMemo(() => getActiveMapelList(legacy), [legacy]);
  const [filterTingkat, setFilterTingkat] = useState<'all' | TingkatKelas>('all');
  const [selectedKelasId, setSelectedKelasId] = useState<string>(
    adminState.classes[0]?.id || 'kls_10_a'
  );
  const [semester, setSemester] = useState<1 | 2>(1);
  const [selectedMapel, setSelectedMapel] = useState<string>(mapelList[0] || 'Mata Pelajaran Utama');

  // Inline replace confirmation state when auto-generated rows already exist
  const [pendingGenerated, setPendingGenerated] = useState<{
    items: JournalItem[];
    sourceNote: string;
  } | null>(null);

  // Manual entry modal/drawer
  const [showAddForm, setShowAddForm] = useState(false);
  const [mTanggal, setMTanggal] = useState(() => {
    const d = new Date();
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  });
  const [mJp, setMJp] = useState(2);
  const [mTpLabel, setMTpLabel] = useState('');
  const [mMateri, setMMateri] = useState('');
  const [mCatatan, setMCatatan] = useState('');

  const visibleClasses = useMemo(() => {
    if (filterTingkat === 'all') return adminState.classes;
    return adminState.classes.filter((c) => c.tingkat === filterTingkat);
  }, [adminState.classes, filterTingkat]);

  const activeKelas = useMemo(
    () => adminState.classes.find((c) => c.id === selectedKelasId) || visibleClasses[0],
    [adminState.classes, selectedKelasId, visibleClasses]
  );
  const effectiveKelasId = activeKelas?.id || selectedKelasId;

  const studentsInClass = useMemo(
    () => adminState.students.filter((s) => s.kelasId === effectiveKelasId && s.status !== 'nonaktif'),
    [adminState.students, effectiveKelasId]
  );

  const filteredJournals = useMemo(() => {
    return adminState.journals
      .filter(
        (j) =>
          j.kelasId === effectiveKelasId &&
          j.semester === semester &&
          (!j.mapel || j.mapel === selectedMapel)
      )
      .sort((a, b) => a.tanggal.localeCompare(b.tanggal));
  }, [adminState.journals, effectiveKelasId, semester, selectedMapel]);

  const handleAutoGenerate = () => {
    const { items, sourceNote } = autoGenerateJournals(effectiveKelasId, semester, selectedMapel);
    if (items.length === 0) {
      api?.toast(sourceNote);
      return;
    }

    const hasExisting = filteredJournals.some((j) => j.autoGenerated);
    if (hasExisting) {
      setPendingGenerated({ items, sourceNote });
      return;
    }

    const updated = updateAdminGuruState((prev) => ({
      ...prev,
      journals: [...prev.journals, ...items],
    }));
    setAdminState(updated);
    api?.toast(sourceNote);
  };

  const applyPendingGenerated = (mode: 'replace' | 'append') => {
    if (!pendingGenerated) return;
    const updated = updateAdminGuruState((prev) => {
      const kept =
        mode === 'replace'
          ? prev.journals.filter(
              (j) =>
                !(
                  j.kelasId === effectiveKelasId &&
                  j.semester === semester &&
                  (!j.mapel || j.mapel === selectedMapel) &&
                  j.autoGenerated
                )
            )
          : prev.journals;
      return {
        ...prev,
        journals: [...kept, ...pendingGenerated.items],
      };
    });
    setAdminState(updated);
    api?.toast(pendingGenerated.sourceNote);
    setPendingGenerated(null);
  };

  const handleAddManual = (e: React.FormEvent) => {
    e.preventDefault();
    if (!mMateri.trim() && !mTpLabel.trim()) {
      api?.toast('Isi Tujuan Pembelajaran atau Materi Pokok.');
      return;
    }
    const cal = getDayCalendarStatus(mTanggal);
    const entry: JournalItem = {
      id: createUid('jrn'),
      kelasId: effectiveKelasId,
      semester,
      tanggal: mTanggal,
      hari: cal.hari || getIndonesianDayName(mTanggal),
      pekanKe: 0,
      jpCount: Number(mJp) || 2,
      mapel: selectedMapel,
      tpLabel: mTpLabel.trim() || mMateri.trim(),
      materi: mMateri.trim() || mTpLabel.trim(),
      catatan: mCatatan.trim(),
      refleksi: '',
      status: 'terlaksana',
      autoGenerated: false,
    };
    const updated = updateAdminGuruState((prev) => ({
      ...prev,
      journals: [...prev.journals, entry],
    }));
    setAdminState(updated);
    setShowAddForm(false);
    setMTpLabel('');
    setMMateri('');
    setMCatatan('');
    api?.toast('Entri jurnal manual ditambahkan.');
  };

  const handleUpdateField = (
    id: string,
    patch: Partial<Pick<JournalItem, 'materi' | 'catatan' | 'refleksi' | 'status' | 'tanggal' | 'jpCount'>>
  ) => {
    const updated = updateAdminGuruState((prev) => ({
      ...prev,
      journals: prev.journals.map((j) => {
        if (j.id !== id) return j;
        const next = { ...j, ...patch };
        if (patch.tanggal) {
          next.hari = getIndonesianDayName(patch.tanggal);
        }
        return next;
      }),
    }));
    setAdminState(updated);
  };

  const handleDeleteJournal = (id: string) => {
    const updated = updateAdminGuruState((prev) => ({
      ...prev,
      journals: prev.journals.filter((j) => j.id !== id),
    }));
    setAdminState(updated);
    api?.toast('Baris jurnal dihapus.');
  };

  const ident = legacy?.identitas || {};
  const signHtml = api ? api.signHTML() : '';

  return (
    <div className="max-w-[1200px] mx-auto space-y-4">
      <div className="panel noprint !max-w-none">
        <div className="flex flex-wrap items-start justify-between gap-3 border-b border-[#e9e4d4] pb-3 mb-4">
          <div>
            <h2 className="!border-0 !pb-0 !mb-1">Jurnal Mengajar (Auto-Generate)</h2>
            <p className="hint !mb-0">
              Menarik otomatis <b>TP &amp; Materi</b> dari Promes/ATP serta <b>Tanggal Efektif</b> dari Kalender Pendidikan &amp; RPE (melewati hari libur), terintegrasi langsung dengan rekap kehadiran <b>Absensi Siswa</b>.
            </p>
          </div>
          <div className="flex flex-wrap gap-2">
            <button type="button" className="btn sm" onClick={() => setShowAddForm((v) => !v)}>
              <Plus className="w-4 h-4" />
              Tambah Manual
            </button>
            <button type="button" className="btn primary" onClick={handleAutoGenerate}>
              <Sparkles className="w-4 h-4" />
              Auto-Generate dari Promes &amp; Kalender
            </button>
            <button type="button" className="btn sm" onClick={() => window.print()}>
              <Printer className="w-4 h-4" />
              Cetak / PDF
            </button>
          </div>
        </div>

        {/* Filter Bar */}
        <div className="grid grid-cols-1 md:grid-cols-12 gap-3 items-end">
          <div className="md:col-span-3">
            <label className="f">Filter Tingkat</label>
            <div className="flex gap-1.5 flex-wrap">
              {(['all', '10', '11', '12'] as const).map((t) => (
                <button
                  key={t}
                  type="button"
                  className={`btn sm ${filterTingkat === t ? 'primary' : ''}`}
                  onClick={() => {
                    setFilterTingkat(t);
                    const first =
                      t === 'all'
                        ? adminState.classes[0]
                        : adminState.classes.find((c) => c.tingkat === t);
                    if (first) setSelectedKelasId(first.id);
                  }}
                >
                  {t === 'all' ? 'Semua' : `Kls ${t}`}
                </button>
              ))}
            </div>
          </div>

          <div className="md:col-span-3">
            <label className="f">Kelas / Rombel</label>
            <select
              className="in"
              value={effectiveKelasId}
              onChange={(e) => setSelectedKelasId(e.target.value)}
            >
              {visibleClasses.map((c) => (
                <option key={c.id} value={c.id}>
                  Kelas {c.tingkat} — {c.nama}
                </option>
              ))}
            </select>
          </div>

          <div className="md:col-span-3">
            <label className="f">Semester</label>
            <select
              className="in"
              value={semester}
              onChange={(e) => setSemester(Number(e.target.value) === 2 ? 2 : 1)}
            >
              <option value={1}>Semester 1 (Ganjil)</option>
              <option value={2}>Semester 2 (Genap)</option>
            </select>
          </div>

          <div className="md:col-span-3">
            <label className="f">Mata Pelajaran</label>
            <select
              className="in"
              value={selectedMapel}
              onChange={(e) => setSelectedMapel(e.target.value)}
            >
              {mapelList.map((m) => (
                <option key={m} value={m}>
                  {m}
                </option>
              ))}
            </select>
          </div>
        </div>
      </div>

      {/* Konfirmasi Auto-Generate jika sudah ada data auto-generated */}
      {pendingGenerated && (
        <div className="panel noprint !max-w-none border-l-4 border-l-[#c7a45b]">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div>
              <h2 className="!border-0 !pb-0 !mb-1">Jurnal Otomatis Sudah Ada di Semester Ini</h2>
              <p className="hint !mb-0">
                Ditemukan {pendingGenerated.items.length} pertemuan baru dari Promes &amp; Kalender. Pilih untuk mengganti baris hasil auto-generate sebelumnya atau menambahkannya di bawah.
              </p>
            </div>
            <div className="flex flex-wrap gap-2">
              <button
                type="button"
                className="btn sm"
                onClick={() => setPendingGenerated(null)}
              >
                Batal
              </button>
              <button
                type="button"
                className="btn sm"
                onClick={() => applyPendingGenerated('append')}
              >
                Tambahkan Saja
              </button>
              <button
                type="button"
                className="btn sm primary"
                onClick={() => applyPendingGenerated('replace')}
              >
                Perbarui / Ganti Otomatis
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Form Tambah Jurnal Manual */}
      {showAddForm && (
        <div className="panel noprint !max-w-none border-l-4 border-l-[#126451]">
          <h2>Tambah Entri Jurnal Mengajar</h2>
          <form onSubmit={handleAddManual} className="grid grid-cols-1 md:grid-cols-12 gap-3 items-end">
            <div className="md:col-span-3">
              <label className="f">Tanggal Pertemuan</label>
              <input
                type="date"
                className="in"
                value={mTanggal}
                onChange={(e) => setMTanggal(e.target.value)}
                required
              />
            </div>
            <div className="md:col-span-2">
              <label className="f">Jumlah JP</label>
              <input
                type="number"
                min={1}
                max={12}
                className="in"
                value={mJp}
                onChange={(e) => setMJp(Number(e.target.value))}
              />
            </div>
            <div className="md:col-span-7">
              <label className="f">Tujuan Pembelajaran (TP)</label>
              <input
                className="in"
                placeholder="Ringkasan TP pertemuan ini"
                value={mTpLabel}
                onChange={(e) => setMTpLabel(e.target.value)}
              />
            </div>
            <div className="md:col-span-6">
              <label className="f">Materi Pokok / Kegiatan *</label>
              <input
                className="in"
                placeholder="Materi yang diajarkan"
                value={mMateri}
                onChange={(e) => setMMateri(e.target.value)}
                required
              />
            </div>
            <div className="md:col-span-6">
              <label className="f">Catatan Awal</label>
              <input
                className="in"
                placeholder="Catatan kelas atau kendala (opsional)"
                value={mCatatan}
                onChange={(e) => setMCatatan(e.target.value)}
              />
            </div>
            <div className="md:col-span-12 flex justify-end gap-2">
              <button type="button" className="btn sm" onClick={() => setShowAddForm(false)}>
                Batal
              </button>
              <button type="submit" className="btn sm primary">
                Simpan Jurnal
              </button>
            </div>
          </form>
        </div>
      )}

      {/* Tabel Kerja Jurnal Mengajar */}
      <div className="panel noprint !max-w-none">
        {filteredJournals.length === 0 ? (
          <div className="empty">
            <b>Belum ada entri Jurnal Mengajar pada filter ini</b>
            <span>
              Klik tombol <b>Auto-Generate dari Promes &amp; Kalender</b> untuk menyusun jadwal pertemuan otomatis dari Promes, ATP, Jadwal Mengajar, dan Kalender Pendidikan (otomatis melewati hari libur).
            </span>
          </div>
        ) : (
          <div className="tw">
            <table className="work">
              <thead>
                <tr>
                  <th className="c w-10">No</th>
                  <th className="w-40">Tanggal &amp; Hari</th>
                  <th className="c w-20">Pekan / JP</th>
                  <th className="min-w-[210px]">TP &amp; Materi (Dari Promes)</th>
                  <th className="w-44">Rekap Absensi</th>
                  <th className="min-w-[200px]">Catatan &amp; Refleksi Guru</th>
                  <th className="w-32">Status</th>
                  <th className="c w-14">Hapus</th>
                </tr>
              </thead>
              <tbody>
                {filteredJournals.map((j, idx) => {
                  const att = computeAttendanceSummary(
                    adminState.attendance,
                    effectiveKelasId,
                    j.tanggal,
                    studentsInClass
                  );
                  const cal = getDayCalendarStatus(j.tanggal);
                  return (
                    <tr key={j.id}>
                      <td className="c">{idx + 1}</td>
                      <td>
                        <input
                          type="date"
                          className="in !py-1 !px-1.5 text-xs mb-1"
                          value={j.tanggal}
                          onChange={(e) => handleUpdateField(j.id, { tanggal: e.target.value })}
                        />
                        <div className="text-[11px] text-[#64736c] flex items-center gap-1">
                          <CalendarRange className="w-3 h-3" />
                          <span>{j.hari || cal.hari}</span>
                          {!cal.isEffective && (
                            <span className="text-[#b3261e] font-semibold">({cal.liburCode || 'Non-Efektif'})</span>
                          )}
                        </div>
                      </td>
                      <td className="c">
                        <div className="text-xs font-semibold text-[#0b3c32]">
                          {j.pekanKe > 0 ? `Pekan ${j.pekanKe}` : 'Manual'}
                        </div>
                        <div className="mt-1 flex items-center justify-center gap-1 text-xs">
                          <input
                            type="number"
                            min={1}
                            max={12}
                            className="cell !w-12"
                            value={j.jpCount}
                            onChange={(e) =>
                              handleUpdateField(j.id, { jpCount: Math.max(1, Number(e.target.value) || 1) })
                            }
                          />
                          <span>JP</span>
                        </div>
                      </td>
                      <td>
                        <div className="text-xs font-bold text-[#126451] mb-1 line-clamp-2" title={j.tpLabel}>
                          {j.tpLabel}
                        </div>
                        <textarea
                          rows={2}
                          className="in text-xs !py-1"
                          value={j.materi}
                          onChange={(e) => handleUpdateField(j.id, { materi: e.target.value })}
                          placeholder="Materi / sub-materi..."
                        />
                      </td>
                      <td>
                        {studentsInClass.length === 0 ? (
                          <span className="text-xs text-[#64736c]">Belum ada data siswa</span>
                        ) : att.recorded ? (
                          <div className="space-y-1 text-xs">
                            <div className="flex flex-wrap gap-1">
                              <span className="px-1.5 py-0.5 rounded bg-[#e1f3e8] text-[#1c7a45] font-bold">
                                H: {att.H}
                              </span>
                              <span className="px-1.5 py-0.5 rounded bg-[#d6e8fb] text-[#134f8a] font-bold">
                                S: {att.S}
                              </span>
                              <span className="px-1.5 py-0.5 rounded bg-[#fdf0c8] text-[#7a5200] font-bold">
                                I: {att.I}
                              </span>
                              <span className="px-1.5 py-0.5 rounded bg-[#f9d6d3] text-[#b3261e] font-bold">
                                A: {att.A}
                              </span>
                            </div>
                            <div className="text-[11px] text-[#64736c]">
                              Tidak hadir: {att.S + att.I + att.A} / {att.total} siswa
                            </div>
                          </div>
                        ) : (
                          <div className="text-xs text-[#8b6416]">
                            <div className="flex items-center gap-1">
                              <Users className="w-3.5 h-3.5" />
                              <span>Belum diabsen</span>
                            </div>
                            <a href="#/absensi" className="underline text-[11px] font-semibold">
                              Isi absensi →
                            </a>
                          </div>
                        )}
                      </td>
                      <td>
                        <textarea
                          rows={1}
                          className="in text-xs !py-1 mb-1"
                          placeholder="Catatan pelaksanaan..."
                          value={j.catatan}
                          onChange={(e) => handleUpdateField(j.id, { catatan: e.target.value })}
                        />
                        <textarea
                          rows={1}
                          className="in text-xs !py-1"
                          placeholder="Refleksi guru / tindak lanjut..."
                          value={j.refleksi}
                          onChange={(e) => handleUpdateField(j.id, { refleksi: e.target.value })}
                        />
                      </td>
                      <td>
                        <select
                          className={`fsel ${
                            j.status === 'terlaksana'
                              ? 'v-SB'
                              : j.status === 'ditunda'
                                ? 'v-K'
                                : 'v-C'
                          }`}
                          value={j.status}
                          onChange={(e) =>
                            handleUpdateField(j.id, {
                              status: e.target.value as JournalItem['status'],
                            })
                          }
                        >
                          <option value="terjadwal">Terjadwal</option>
                          <option value="terlaksana">Terlaksana</option>
                          <option value="ditunda">Ditunda</option>
                        </select>
                      </td>
                      <td className="c">
                        <button
                          type="button"
                          className="btn sm danger"
                          title="Hapus baris jurnal"
                          onClick={() => handleDeleteJournal(j.id)}
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* Dokumen Cetak Resmi (Landscape A4/F4) */}
      {filteredJournals.length > 0 && (
        <div className="paper land">
          <div className="dt">JURNAL MENGAJAR HARIAN GURU</div>
          <div className="dt2">{ident.namaSekolah || 'MADRASAH ALIYAH BANU HASYIM'}</div>
          <table className="info">
            <tbody>
              <tr>
                <td>Mata Pelajaran</td>
                <td>: {selectedMapel}</td>
                <td style={{ paddingLeft: 28 }}>Kelas / Rombel</td>
                <td>: {activeKelas?.nama || '-'} (Kelas {activeKelas?.tingkat || '-'})</td>
              </tr>
              <tr>
                <td>Semester / Tahun Pelajaran</td>
                <td>: {semester === 2 ? 'Genap (2)' : 'Ganjil (1)'} / {ident.tahun || '-'}</td>
                <td style={{ paddingLeft: 28 }}>Guru Mata Pelajaran</td>
                <td>: {ident.guru || '-'}</td>
              </tr>
            </tbody>
          </table>

          <table className="doc sm">
            <thead>
              <tr>
                <th className="c" style={{ width: '4%' }}>No</th>
                <th style={{ width: '13%' }}>Hari / Tanggal</th>
                <th className="c" style={{ width: '6%' }}>JP</th>
                <th style={{ width: '24%' }}>Tujuan Pembelajaran (TP)</th>
                <th style={{ width: '22%' }}>Materi / Kegiatan</th>
                <th className="c" style={{ width: '11%' }}>Absensi (H/S/I/A)</th>
                <th style={{ width: '20%' }}>Catatan &amp; Refleksi Guru</th>
              </tr>
            </thead>
            <tbody>
              {filteredJournals.map((j, idx) => {
                const att = computeAttendanceSummary(
                  adminState.attendance,
                  effectiveKelasId,
                  j.tanggal,
                  studentsInClass
                );
                return (
                  <tr key={j.id}>
                    <td className="c">{idx + 1}</td>
                    <td>
                      <b>{j.hari}</b>
                      <br />
                      {formatTanggalID(j.tanggal)}
                    </td>
                    <td className="c">{j.jpCount}</td>
                    <td>{j.tpLabel}</td>
                    <td>{j.materi}</td>
                    <td className="c">
                      {att.recorded
                        ? `H:${att.H} S:${att.S} I:${att.I} A:${att.A}`
                        : '-'}
                    </td>
                    <td>
                      {[j.catatan, j.refleksi].filter(Boolean).join(' · ') || '-'}
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
          {signHtml && <div dangerouslySetInnerHTML={{ __html: signHtml }} />}
        </div>
      )}
    </div>
  );
};
